package com.whattoeat.room.domain;

/**
 * 방의 진행 단계. 대기 중 → 제안 중 → 합치기 중 → 투표 중 → (재투표 중) → 종료.
 * 아무도 메뉴를 내지 않았거나 아무도 투표하지 않으면 랜덤 선택으로 간다.
 */
public enum RoomStatus {

	/** 방을 만든 직후. 방장이 "시작"을 누르면 제안 단계로 넘어간다. */
	WAITING,

	/** 메뉴 제안 단계. 시간이 다 되거나, 모두 끝내거나, 방장이 "다음 단계로"를 누르면 넘어간다. */
	PROPOSING,

	/** 비슷한 메뉴 합치기 단계. 메뉴가 2개 이상일 때만 열린다. 넘어가는 조건은 제안 단계와 같다. */
	MERGING,

	/** 투표 단계. 남은 메뉴가 2개 이상일 때만 열린다. 넘어가는 조건은 제안 단계와 같다. */
	VOTING,

	/** 투표에서 동점이 나왔을 때, 동점 메뉴만 놓고 한 번 더 하는 투표. 투표와 같은 규칙, 같은 시간이다. */
	REVOTING,

	/**
	 * 아무도 메뉴를 제안하지 않았거나 아무도 투표하지 않았을 때 가는 단계.
	 * 서버가 참여자 중 한 명을 무작위로 뽑고, 그 사람이 메뉴 이름을 정한다. 시간 안에 안 정하면 다른 사람을 다시 뽑는다.
	 */
	RANDOM_PICK,

	/** 메뉴가 결정되어 끝난 상태. 더 넘어갈 단계가 없고, 새로 들어올 수 없다. */
	FINISHED

}
