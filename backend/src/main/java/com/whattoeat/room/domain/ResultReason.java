package com.whattoeat.room.domain;

/**
 * 메뉴가 어떻게 결정됐는지. 결과 화면에 한 줄로 보여준다.
 */
public enum ResultReason {

	/** 제안이 끝났을 때나 합치기가 끝난 뒤 메뉴가 하나뿐이라 투표 없이 정해졌다. */
	ONLY_MENU,

	/** 투표에서 1등이 하나였다. */
	VOTE,

	/** 투표가 동점이라 재투표를 했고, 재투표에서 1등이 하나였다. */
	REVOTE,

	/** 재투표도 동점이거나 아무도 찍지 않아서, 서버가 동점 메뉴 중 무작위로 골랐다. */
	REVOTE_RANDOM,

	/** 랜덤 선택에서 뽑힌 사람이 메뉴 이름을 정했다. 누가 정했는지는 비밀이다. */
	PICKED

}
